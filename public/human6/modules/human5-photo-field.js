// Shared by the local template preview and the optional Human5 bridge.
const clamp=(v,a,b)=>Math.max(a,Math.min(b,v));
const smooth=t=>{t=clamp(t,0,1);return t*t*(3-2*t);};
const bell=(v,c,w)=>Math.exp(-(((v-c)/w)**2));
export function identityWarp(x,y,z,s={}){
 if(y<1.395)return [x,y,z];
 const front=smooth((z+.012)/.05),eye=bell(Math.abs(x),.031,.022)*bell(y,1.513,.017)*front;
 return [x+x*((s.jawWidth||0)*bell(y,1.431,.025)*front+(s.craniumWidth||0)*bell(y,1.615,.07))+(x-Math.sign(x)*.031)*(s.eyeWidth||0)*eye,
 y+(s.chinLength||0)*bell(y,1.408,.014)*bell(x,0,.04)+(s.browHeight||0)*bell(y,1.545,.013)*front+(y-1.513)*(s.eyeAperture||0)*eye,
 z+(s.cheekFullness||0)*bell(y,1.483,.022)*bell(Math.abs(x),.042,.028)*front+(s.noseProjection||0)*bell(x,0,.017)*bell(y,1.480,.021)*front+(s.lipFullness||0)*bell(x,0,.03)*bell(y,1.448,.01)*front];
}
export function validateField(f){
 if(!f||f.format!=='human5.face-field/1')throw Error('Unknown face field format');
 for(const [key,min,max] of [['radius',.03,.10],['maxDisplacement',0,.012],['strength',0,1]])if(typeof f[key]!=='number'||!Number.isFinite(f[key])||f[key]<min||f[key]>max)throw Error('Invalid '+key);
 if(f.protectEyesNose!==undefined&&typeof f.protectEyesNose!=='boolean')throw Error('Invalid eye protection');
 if(!Array.isArray(f.centers)||!f.centers.length||f.centers.length>64||f.centers.length!==f.coefficients?.length)throw Error('Invalid face field anchors');
 for(let i=0;i<f.centers.length;i++){
  const c=f.centers[i],w=f.coefficients[i];
  if(!Array.isArray(c)||c.length!==3||!Array.isArray(w)||w.length!==3||![...c,...w].every(Number.isFinite)||Math.abs(c[0])>.2||c[1]<1.35||c[1]>1.7||Math.abs(c[2])>.25||w.some(v=>Math.abs(v)>.08))throw Error('Face field exceeds template bounds');
 }
 return structuredClone(f);
}
export function fieldDelta(x,y,z,f){
 if(!f||!f.strength||y<=1.39||z<=-.02)return [0,0,0];
 let dx=0,dy=0,dz=0;
 for(let i=0;i<f.centers.length;i++){
  const c=f.centers[i],r=Math.hypot(x-c[0],y-c[1],z-c[2])/f.radius;if(r>=1)continue;
  const k=(1-r)**4*(4*r+1),w=f.coefficients[i];dx+=k*w[0];dy+=k*w[1];dz+=k*w[2];
 }
 if(f.protectEyesNose){
  // Residual cheek/jaw interpolation must not displace the cornea or tilt the tip.
  // Primary eye proportions remain in identityWarp; this only damps the extra field.
  const ocular=bell(Math.abs(x),.031,.016)*bell(y,1.513,.011)*smooth((z-.045)/.025);
  dy*=1-.80*ocular;dz*=1-.95*ocular;
  const nasal=(1-smooth((Math.abs(x)-.013)/.010))*(1-smooth((Math.abs(y-1.480)-.014)/.014))*smooth((z-.073)/.020);
  dy*=1-nasal;dz*=1-nasal;
 }
 const gate=smooth((y-1.39)/.025)*smooth((z+.02)/.04)*f.strength;
 const scale=gate*Math.min(1,f.maxDisplacement/Math.max(1e-12,Math.hypot(dx,dy,dz)));
 return [dx*scale,dy*scale,dz*scale];
}
export function deformGeometry(geometry,field){
 const p=geometry.attributes.position,src=Float32Array.from(p.array),morphs=geometry.morphAttributes.position||[];
 // Rebase expression endpoints through the same field. This is performed on import
 // / shape edits only, never every rendered frame. Rest arrays are regenerated by Human5.
 for(let i=0;i<p.count;i++){
  const j=i*3,x=src[j],y=src[j+1],z=src[j+2];if(y<1.385)continue;
  const d=fieldDelta(x,y,z,field);p.array[j]+=d[0];p.array[j+1]+=d[1];p.array[j+2]+=d[2];
  for(const attr of morphs){const a=attr.array,e=fieldDelta(x+a[j],y+a[j+1],z+a[j+2],field);a[j]+=e[0]-d[0];a[j+1]+=e[1]-d[1];a[j+2]+=e[2]-d[2];}
 }
 p.needsUpdate=true;for(const m of morphs)m.needsUpdate=true;
 geometry.computeVertexNormals();geometry.computeBoundingSphere();return geometry;
}
